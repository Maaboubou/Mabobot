def start_wechat_logic():
    """初始化微信并保持运行，支持自动重连"""
    global wx, restart_requested, wechat_connection_generation

    retry_count = 0
    max_retries = 3
    base_delay = 10  # 基础重连延迟

    while True:
        current_client = None
        manual_restart = False
        retry_delay = base_delay
        disconnect_reason = "connection_cycle_end"
        try:
            # 在新线程中必须初始化COM
            comtypes.CoInitialize()

            logger.info(f"Initializing WeChat... (attempt {retry_count + 1})")
            # 只原子发布客户端引用；真实 UI 串行由 mabowx 负责。
            with wx_client_lock:
                current_client = WeChat(start_listener=True)
                wx = current_client
                wechat_connection_generation += 1
                _online_probe_mark_connected()
                _reset_listener_recovery_after_connection()
            logger.info(
                "✅ WeChat connected successfully! connection_id=%s:%s",
                wechat_service_instance_id,
                wechat_connection_generation,
            )
            # 重置重试计数
            retry_count = 0

            # 启动KeepRunning在单独线程中，然后进入监控循环
            logger.info("Starting KeepRunning in background...")
            # 必须捕获本轮对象；不能让旧线程在重连后读取新的全局 wx。
            keep_running_thread = threading.Thread(
                target=current_client.KeepRunning,
                name="mabowx_keep_running",
                daemon=True,
            )
            keep_running_thread.start()

            # 进入监控循环，定期检查重启请求和微信状态
            logger.info("Starting monitoring loop...")
            while True:
                # 检查重启请求
                if restart_requested:
                    logger.info("🔄 检测到重启请求，退出当前连接...")
                    restart_requested = False
                    manual_restart = True
                    disconnect_reason = "manual_restart"
                    break

                probe_started = time.perf_counter()
                if wx is not current_client:
                    disconnect_reason = "connection_replaced"
                    break
                try:
                    online = bool(current_client.IsOnline())
                    duration_ms = (time.perf_counter() - probe_started) * 1000
                    probe = _online_probe_record_result(online, duration_ms)
                except Exception as check_e:
                    duration_ms = (time.perf_counter() - probe_started) * 1000
                    probe = _online_probe_record_error(check_e, duration_ms)

                if not probe.get("online"):
                    logger.warning(
                        "⚠️ 微信在线状态已确认异常，将重新连接: state=%s "
                        "failures=%s/%s kind=%s error=%s duration_ms=%s",
                        probe.get("state"),
                        probe.get("consecutive_failures"),
                        probe.get("failure_threshold"),
                        probe.get("last_failure_kind"),
                        probe.get("last_error"),
                        probe.get("last_duration_ms"),
                    )
                    disconnect_reason = "wechat_offline_confirmed"
                    break

                if probe.get("state") == "suspect":
                    logger.debug(
                        "微信在线探针瞬时失败，保留已确认连接: failures=%s/%s "
                        "kind=%s error=%s duration_ms=%s",
                        probe.get("consecutive_failures"),
                        probe.get("failure_threshold"),
                        probe.get("last_failure_kind"),
                        probe.get("last_error"),
                        probe.get("last_duration_ms"),
                    )

                # 等待5秒后再次检查
                time.sleep(ONLINE_PROBE_INTERVAL_SEC)

            # 退出监控循环，准备重连
            logger.info("🔄 准备重新连接...")

        except Exception as e:
            logger.error(f"❌ WeChat connection failed: {e}", exc_info=True)
            disconnect_reason = f"connection_failed:{e}"
            retry_count += 1

            if retry_count > max_retries:
                logger.error(f"❌ WeChat connection failed after {max_retries} attempts, entering continuous retry mode")
                # 进入持续重试模式，但延长间隔
                retry_delay = min(300, base_delay * (2 ** min(retry_count - max_retries, 5)))  # 最多5分钟
            else:
                retry_delay = base_delay * retry_count

            logger.info(f"🔄 Will retry WeChat connection in {retry_delay} seconds...")

        finally:
            with wx_client_lock:
                if wx is current_client:
                    wx = None
                _stop_wechat_client(current_client, disconnect_reason)
            _online_probe_mark_disconnected(disconnect_reason)

            # 确保COM被正确卸载
            try:
                comtypes.CoUninitialize()
            except Exception:
                pass

        # 确定重连延迟时间
        if manual_restart:
            logger.info("🔄 手动重启，立即尝试重连...")
            delay = 2  # 手动重启短暂等待
        else:
            # 自动重连：使用计算的延迟或默认值
            delay = retry_delay
            logger.info(f"🔄 等待 {delay} 秒后重连...")

        time.sleep(delay)

        logger.info("🔄 Attempting to reconnect WeChat...")


def check_summary_permission(chat_name: str) -> bool:
    """
    检查聊天是否启用了摘要功能
    
    Args:
        chat_name: 聊天名称
        
    Returns:
        是否启用摘要功能
    """
    try:
        # 从数据库查询用户权限
        db = SessionLocal()
        try:
            user = db.query(WeChatUser).filter(WeChatUser.chat_name == chat_name).first()
            if user:
                # 检查用户是否有摘要插件权限
                allowed_plugins = {p.plugin_name for p in user.permissions}
                summary_plugins = {"builtin_summary", "summary_plus"}
                # 支持多级目录插件名匹配（完整键）
                if allowed_plugins.intersection(summary_plugins):
                    return True
                # 检查末级简名匹配
                base_plugins = {p.rsplit('/', 1)[-1] for p in allowed_plugins}
                if base_plugins.intersection(summary_plugins):
                    return True
                return False
            else:
                # 如果用户不在权限表中，默认允许（保持向后兼容）
                logger.debug(f"用户 '{chat_name}' 不在权限表中，默认允许摘要功能")
                return True
        finally:
            db.close()
    except Exception as e:
        logger.warning(f"⚠️ 检查摘要权限失败: {e}")
        # 如果检查失败，默认允许（保持向后兼容）
        return True









































