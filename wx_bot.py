@app.route('/api/download_image_message', methods=['POST'])
def download_image_message():
    """下载指定消息ID的图片消息"""
    if not wx:
        return jsonify({"status": "error", "message": "WeChat not connected"}), 503

    data = request.json
    chat_name = data.get('chat_name')
    message_id = data.get('message_id')

    if not chat_name or not message_id:
        return jsonify({"status": "error", "message": "Missing 'chat_name' or 'message_id'"}), 400

    # 从缓存中获取消息对象
    msg = _get_cached_message(chat_name, message_id)
    if msg is None:
        return jsonify({"status": "error", "message": "Message not found in cache"}), 404

    cache_key = ("image", chat_name, message_id)
    request_id = uuid.uuid4().hex

    def _download_once() -> str:
        logger.info("Downloading image message once: %s:%s type=%s request_id=%s", chat_name, message_id, type(msg), request_id)
        with media_download_trace(msg, request_id=request_id, chat=chat_name, message_id=message_id):
            file_path = msg.download()
        logger.info("Download completed, result: %s", file_path)
        if isinstance(file_path, dict):
            raise RuntimeError(str(file_path.get("message") or file_path))
        normalized_path = str(file_path or "")
        if not normalized_path:
            raise RuntimeError("Download returned no file path")
        if not os.path.exists(normalized_path):
            raise FileNotFoundError(f"Downloaded file does not exist: {normalized_path}")
        _log_image_download_audit("image", chat_name, message_id, normalized_path, msg=msg)
        return normalized_path

    try:
        file_path = media_download_deduplicator.run(
            cache_key,
            _download_once,
            cache_validator=lambda value: os.path.exists(str(value)),
        )
        logger.info("Successfully resolved image download: %s", file_path)
        return jsonify({"status": "success", "file_path": file_path})
    except TimeoutError as e:
        logger.warning("Image download is still in progress: %s:%s", chat_name, message_id)
        response = jsonify({"status": "busy", "message": str(e)})
        response.status_code = 503
        response.headers["Retry-After"] = "5"
        return response
    except MediaFileMismatchError as e:
        get_media_audit = getattr(msg, "get_media_audit", None)
        verification = dict(get_media_audit() if callable(get_media_audit) else {})
        rejected_path = str(verification.get("candidate_path") or "")
        if rejected_path and os.path.isfile(rejected_path):
            _log_image_download_audit(
                "image_rejected",
                chat_name,
                message_id,
                rejected_path,
                msg=msg,
            )
        else:
            logger.warning(
                "图片绑定拒绝: chat=%r message_id=%s reason=%s",
                chat_name,
                message_id,
                e,
            )
        return jsonify({
            "status": "identity_rejected",
            "error_code": "image_identity_mismatch",
            "message": str(e),
        }), 422
    except MediaIdentityError as e:
        logger.warning(
            "图片界面身份暂时失效: chat=%r message_id=%s reason=%s",
            chat_name,
            message_id,
            e,
        )
        response = jsonify({
            "status": "retryable",
            "error_code": "image_ui_identity_changed",
            "message": str(e),
        })
        response.status_code = 503
        response.headers["Retry-After"] = "1"
        return response
    except Exception as e:
        logger.error(
            "图片下载发生未预期错误: chat=%r message_id=%s error=%s request_id=%s",
            chat_name,
            message_id,
            e,
            request_id,
            exc_info=True,
        )
        return jsonify({
            "status": "error",
            "error_code": "image_download_internal_error",
            "message": str(e),
        }), 500






